/** 对当前打开的 ROM 判断某条技巧是否适用 */
export function checkApplicable(
  rom: { data: Buffer; platform: string } | null,
  require?: 'jpGS' | 'enGS' | 'gen1'
): { status: 'ok' | 'warn' | 'no'; text: string } | null {
  if (!rom) return null
  if (rom.platform !== 'gb') return { status: 'no', text: '❌ 此技巧适用于 GB/GBC 版宝可梦' }
  const d = rom.data
  const isJP = d[0x142] === 0x4a // game id 尾字节 'J' = 日版
  const isCrystal = d.subarray(0x134, 0x134 + 10).toString('latin1').startsWith('PM_CRYSTAL')
  const isGen1 = d.subarray(0x134, 0x134 + 10).toString('latin1').includes('POKEMON')
  if (!require) return { status: 'ok', text: '✅ 此 ROM 适用' }
  if (require === 'gen1') {
    return isGen1
      ? { status: 'ok', text: '✅ 此 ROM 为第一世代（红/绿/蓝/黄），适用' }
      : { status: 'no', text: '❌ 此漏洞仅第一世代（红/绿/蓝/黄）有效，当前 ROM 不适用' }
  }
  if (require === 'jpGS') {
    return isJP && !isCrystal
      ? { status: 'ok', text: '✅ 此 ROM 为日版金银，适用' }
      : { status: 'no', text: '❌ 此漏洞仅日版《金/银》有效，当前 ROM 不适用' }
  }
  // enGS
  if (isJP) return { status: 'no', text: '❌ 此漏洞仅英文版《金/银》有效，当前 ROM 不适用' }
  if (isCrystal) return { status: 'no', text: '❌ 此漏洞仅英文版《金/银》有效（水晶已修复），当前 ROM 不适用' }
  return { status: 'warn', text: '⚠ 此漏洞在英文原版金银验证过——汉化版若改写过文本区则大概率失效，请实测' }
}

